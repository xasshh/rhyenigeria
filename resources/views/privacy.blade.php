        <p>When you join Renewed Hope Youth Engagement we collect personal data under the <strong>Nigeria Data Protection Act 2023</strong>, on the basis of your consent. This notice explains what we collect, why, and your rights.</p>

        <h2>What we collect</h2>
        <ul class="list-disc space-y-1 pl-5">
            <li>Your name, email address, phone number, gender, age range and occupation.</li>
            <li>Your state, LGA, ward and (if you choose) polling unit.</li>
            <li>Whether you have a PVC and, if you give them, your VIN and NIN. These are encrypted when stored and are never shown in full.</li>
            <li>Your current location, only if you tap "Share my current location".</li>
            <li>If you apply to canvass: how you would like to help and your WhatsApp number.</li>
            <li>If you report an empowerment programme: the details and the photo you upload.</li>
        </ul>

        <h2>Why we use it</h2>
        <p>Only to coordinate the movement: to connect you with your ward and state team, tell you about events and news, issue your membership card, and plan activity in your area.</p>

        <h2>Who can see it</h2>
        <p>Your state coordinator can see the members in their state, and a small national team can see everyone. Phone numbers are masked in lists, and NIN and VIN are never shown in full. Every export of member data is logged. The public page behind your card's QR code shows only your first name and last initial, your state and the month you joined.</p>

        <h2>What we never do</h2>
        <p>We <strong>never sell</strong> your data, and we do not share it with third parties for their own purposes.</p>

        <h2>Your rights</h2>
        <p>You may ask to see, correct or delete your data at any time, and you may withdraw your consent. Ask your state coordinator or contact us through the website, and we will act on it. Deleting your data ends your membership.</p>
